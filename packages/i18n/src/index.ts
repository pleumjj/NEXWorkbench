/**
 * NEX Workbench UI language.
 *
 * English is the source language: UI strings and engine messages are written in English. In Thai, every string React
 * renders passes through `translate()` (see jsx-runtime.ts) — exact phrases from the dictionary, then patterns with
 * placeholders ({n} = a value containing a digit, {s} = any text). Anything unknown stays English, so a missing
 * translation never breaks a page. User data (file names, paths, project names) is never translated: it is rendered
 * inside `translate="no"`, `.mono`, `.path`, <code> or <kbd>.
 *
 * Exports for Claude and CSV files are generated by the engines and stay English by design.
 */
import { TH } from './th';

export type Language = 'en' | 'th';
export type LanguagePreference = 'system' | Language;

let current: Language = 'en';
const listeners = new Set<(l: Language) => void>();
export const getLanguage = () => current;
export function setLanguage(l: Language) {
  if (l === current) return;
  current = l;
  cache.clear();
  listeners.forEach(f => f(l));
}
export const onLanguage = (f: (l: Language) => void) => { listeners.add(f); return () => { listeners.delete(f); }; };
/** "th-TH" / "th" → th; everything else → en. */
export const languageOf = (locale: string | null | undefined): Language => (/^th\b/i.test(locale ?? '') ? 'th' : 'en');

/* ───────────── dictionary ───────────── */

type Pattern = { re: RegExp; value: string };
const exact = new Map<string, string>();
const patterns: Pattern[] = [];
const PLACEHOLDER = /\{(n|s)\}/g;
const escape = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
function compile(dict: Record<string, string>) {
  for (const [en, th] of Object.entries(dict)) {
    if (th == null) continue;
    PLACEHOLDER.lastIndex = 0;
    if (!PLACEHOLDER.test(en)) { exact.set(en, th); continue; }
    PLACEHOLDER.lastIndex = 0;
    // A pattern must carry real words, or it could match (and rewrite) arbitrary user text.
    if (en.replace(PLACEHOLDER, '').replace(/[^A-Za-z]/g, '').length < 3) continue;
    const src = escape(en).replace(/\\\{n\\\}/g, '(\\S*\\d[^\\n]*?)').replace(/\\\{s\\\}/g, '([^\\n]+?)');
    patterns.push({ re: new RegExp(`^${src}$`), value: th });
  }
  // Longer (more specific) patterns first.
  patterns.sort((a, b) => b.re.source.length - a.re.source.length);
}
compile(TH);

/** Fill a Thai value: {0},{1}… by index, or {n}/{s} in order. */
function fill(value: string, groups: string[]) {
  let i = 0;
  return value.replace(/\{(\d+|n|s)\}/g, (_m, k: string) => (/^\d+$/.test(k) ? groups[Number(k)] ?? '' : groups[i++] ?? ''));
}

function lookup(s: string): string | null {
  const hit = exact.get(s);
  if (hit !== undefined) return hit;
  if (!/[A-Za-z]/.test(s)) return null;
  for (const p of patterns) {
    const m = p.re.exec(s);
    if (m) return fill(p.value, m.slice(1).map(g => translate(g)));
  }
  return null;
}

const cache = new Map<string, string>();
/** Strings seen in Thai without a translation (for coverage checks: window.__nexI18nMissing in the browser). */
export const missing = new Set<string>();
(globalThis as Record<string, unknown>).__nexI18nMissing = missing;
/** Translate one UI string into the current language (unchanged in English or when unknown). */
export function translate(s: string): string {
  if (current === 'en' || !s || !/[A-Za-z]/.test(s)) return s;
  const c = cache.get(s);
  if (c !== undefined) return c;
  const lead = s.match(/^\s*/)![0], trail = s.match(/\s*$/)![0];
  const core = s.slice(lead.length, s.length - trail.length);
  let out = lookup(core);
  if (out == null) {
    // Separators belong to the layout ("· Part of …", ". FileNEX never …", "… ·"): try the phrase without them.
    const pre = core.match(/^(?:[·•—–]\s*|\.\s+)*/)![0], post = core.match(/(?:\s*[·•—–])*$/)![0];
    const inner = core.slice(pre.length, core.length - post.length);
    if (inner && inner !== core) { const hit = lookup(inner); if (hit != null) out = pre + hit + post; }
  }
  if (out == null) {
    // Composite messages: "A · B", "Sentence one. Sentence two." — translate the parts that are known.
    const parts = core.split(/( · | — |(?<=[.!?])\s+)/);
    if (parts.length > 1) {
      const tr = parts.map(p => (p.trim() && !/^( · | — |\s+)$/.test(p) ? lookup(p) ?? p : p));
      if (tr.some((p, i) => p !== parts[i])) out = tr.join('');
    }
  }
  if (out == null && missing.size < 5000 && !/[\u0E00-\u0E7F]/.test(core)) missing.add(core);
  const result = out == null ? s : lead + out + trail;
  if (cache.size > 20_000) cache.clear();
  cache.set(s, result);
  return result;
}
/** For strings outside JSX (document.title, confirm text, aria built in code). */
export const t = translate;

/* ───────────── formatting (Gregorian years, Latin digits) ───────────── */

export const localeTag = () => (current === 'th' ? 'th-TH-u-ca-gregory-nu-latn' : undefined);
export const fmtDate = (d: Date | string | number, o?: Intl.DateTimeFormatOptions) => new Date(d).toLocaleDateString(localeTag(), o);
export const fmtTime = (d: Date | string | number, o?: Intl.DateTimeFormatOptions) => new Date(d).toLocaleTimeString(localeTag(), o);
export const fmtDateTime = (d: Date | string | number, o?: Intl.DateTimeFormatOptions) => new Date(d).toLocaleString(localeTag(), o);
export const fmtNumber = (n: number, o?: Intl.NumberFormatOptions) => n.toLocaleString(current === 'th' ? 'th-TH-u-nu-latn' : 'en-US', o);
